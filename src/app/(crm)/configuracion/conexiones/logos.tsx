export type MarcaId = "search_console" | "analytics" | "gmail" | "calendar" | "meta_ads";
export function MarcaServicio({ id, size }: { id: MarcaId; size?: number }): ReactNode {
  switch (id) {
    case "search_console": return <SearchConsoleLogo size={size} />;
    case "analytics": return <AnalyticsLogo size={size} />;
    case "gmail": return <GmailLogo size={size ? size - 4 : undefined} />;
    case "calendar": return <CalendarLogo size={size} />;
    case "meta_ads": return <MetaLogo size={size ? size - 8 : undefined} />;
  }
}
